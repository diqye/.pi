"""Each typed word as specks of light: points inside its letters, on a grid, so the film can take the word apart.
Writes kit/glyphs.gen.ts: for each word its size, its width, and x, y, letter-index triples (x from the word's left
edge, y from its baseline, in px at that size). Letters are placed by the same advance table the film's type uses.
  python tools/glyphs.py     (from anywhere; run it again when a typed word, its size or the font changes)
It reads media/fonts/Geist-VF.ttf (Geist, SIL Open Font License 1.1: media/fonts/OFL-Geist.txt), the same font
kit/fonts.gen.ts embeds for the picture, and kit/metrics.gen.ts. Needs Pillow."""
import json, pathlib
from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent.parent          # the film's folder
FONT = HERE / "media" / "fonts" / "Geist-VF.ttf"
WORDS = {"rain.": 240, "thunder.": 200, "footsteps.": 170, "a clap, with echo.": 118, "a heartbeat.": 130, "hush.": 96}
LS = -0.02
adv_ts = (HERE / "kit" / "metrics.gen.ts").read_text(encoding="utf-8")
ADV = json.loads(adv_ts[adv_ts.index("= ") + 2:adv_ts.rindex(";")])["geist500"]
out = {}
for word, size in WORDS.items():
    font = ImageFont.truetype(str(FONT), size); font.set_variation_by_axes([500])
    step = max(4, round(size / 46)); pts = []; x = 0.0
    for ci, ch in enumerate(word):
        a = (ADV.get(ch, 0.6) + LS) * size
        if ch != " ":
            w, h = int(a + size), int(size * 1.6); im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((size * 0.3, size * 1.1), ch, font=font, fill=255, anchor="ls")     # baseline at 1.1 em
            px = im.load()
            for yy in range(step // 2, h, step):
                for xx in range(step // 2, w, step):
                    if px[xx, yy] > 110: pts += [round(x + xx - size * 0.3, 1), round(yy - size * 1.1, 1), ci]
        x += a
    out[word] = {"size": size, "w": round(x, 1), "step": step, "pts": pts}
    print(f"{word!r}: size {size}, width {x:.0f}, step {step}, {len(pts) // 3} specks")
(HERE / "kit" / "glyphs.gen.ts").write_text("// generated by tools/glyphs.py\nexport const GLYPHS: Record<string, { size: number; w: number; step: number; pts: number[] }> = " + json.dumps(out) + ";\n", encoding="utf-8", newline="\n")
