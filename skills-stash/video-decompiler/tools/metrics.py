#!/usr/bin/env python3
"""A worked film's table of letter widths (kit/metrics.gen.ts), made again for another face.

  python metrics.py SANS-VF.ttf MONO-VF.ttf [--film DIR] [--sans 400,500,600] [--mono 400,500]

The worked films place and size things by the width of words (a bracket round a word, the marks under one, a line typed
letter by letter), so their kit holds each letter's advance width in ems for the faces and weights the film uses. That
table was made from Geist and Geist Mono. Change the running face and it has to be made again from yours, or everything
sized to a word is sized to Geist's letters. Give the two variable fonts (a .ttf with a weight axis each; any other
axis, such as optical size or width, stays at the font's own default); the table
goes to DIR/kit/metrics.gen.ts (DIR: the film folder, default here) under the same names the kit reads
(`geist400`, `mono500`, ...), so no film code changes. Embed the face itself as the film does (kit/fonts.gen.ts: an
`@font-face` with a `data:` URL).

Kerning is not included: widths are within a few px at headline size, which is all the kit uses them for. Needs Pillow.
"""
import argparse
import json
from pathlib import Path

CHARS = [chr(c) for c in range(32, 127)] + list("›·✓…×→—’“”")


def widths(font_file, weights):
    from PIL import ImageFont
    out = {}
    for w in weights:
        font = ImageFont.truetype(str(font_file), 1000)
        try:
            axes = font.get_variation_axes()
        except OSError:
            axes = []
        names = [(a.get("name") or b"") for a in axes]
        names = [(n.decode("utf-8", "replace") if isinstance(n, bytes) else str(n)).strip().lower() for n in names]
        at = next((i for i, n in enumerate(names) if n in ("weight", "wght")), None)
        if at is None:
            raise SystemExit(f"{font_file} has no weight axis to set (its axes: {', '.join(names) or 'none'}): give a variable font, a file named like Name-VF.ttf or Name[wght].ttf")
        vector = [a["default"] for a in axes]     # set by position, so every other axis is given its own default
        vector[at] = w
        font.set_variation_by_axes(vector)
        out[w] = {ch: round(font.getlength(ch) / 1000, 4) for ch in CHARS}
    return out


def table(sans, mono, sans_weights, mono_weights):
    out = {}
    for name, f, weights in (("geist", sans, sans_weights), ("mono", mono, mono_weights)):
        for w, adv in widths(f, weights).items():
            out[f"{name}{w}"] = adv
    return "// generated by tools/metrics.py: advance widths in ems\nexport const ADV: Record<string, Record<string, number>> = " + json.dumps(out, ensure_ascii=False) + ";\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], epilog=__doc__.split("\n\n", 1)[1], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sans", help="the running face, a variable .ttf")
    ap.add_argument("mono", help="the monospaced face, a variable .ttf")
    ap.add_argument("--film", default=".", help="the film folder (default: here)")
    ap.add_argument("--sans", dest="sans_weights", default="400,500,600")
    ap.add_argument("--mono", dest="mono_weights", default="400,500")
    a = ap.parse_args(argv)
    for f in (a.sans, a.mono):
        if not Path(f).is_file():
            raise SystemExit(f"no such font file: {f}")
    kit = Path(a.film) / "kit"
    if not kit.is_dir():
        raise SystemExit(f"{Path(a.film).resolve()} has no kit/ folder: run this in a film folder, or give --film DIR")
    text = table(a.sans, a.mono, [int(w) for w in a.sans_weights.split(",")], [int(w) for w in a.mono_weights.split(",")])
    dest = kit / "metrics.gen.ts"
    dest.write_text(text, encoding="utf-8", newline="\n")
    print(f"{dest}: the widths of {len(CHARS)} characters at {a.sans_weights} ({Path(a.sans).name}) and {a.mono_weights} ({Path(a.mono).name})")


if __name__ == "__main__":
    import utf8  # noqa: F401
    main()
